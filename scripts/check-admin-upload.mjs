assert.match(init,/await isAdmin\(\)/,"Only owners may upload");
assert.match(chunk,/FOR UPDATE/,"Chunk offsets must be transactionally serialized");
assert.match(chunk,/validVideoHeader/,"Uploaded files must be validated");
assert.match(chunk,/readBoundedBody/,"Chunk reading must be memory bounded");
