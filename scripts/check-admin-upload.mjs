assert.match(uploader,/STOP UPLOAD/,"An owner must be able to stop uploads");
assert.match(uploader,/thumbnailFromFile/,"Create thumbnails using video frames");
assert.match(library,/MAKE FEATURED/,"Feature selection must be obvious");
assert.match(library,/Search your Viral library/,"Find videos in a large catalogue");
